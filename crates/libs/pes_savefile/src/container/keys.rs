impl MasterKey {
    /// Every key, in version order; the trial order `decrypt` uses.
    pub(crate) const ALL: [MasterKey; 7] = [
        MasterKey::Pes16,
        MasterKey::Pes16MyClub,
        MasterKey::Pes17,
        MasterKey::Pes18,
        MasterKey::Pes19,
        MasterKey::Pes20,
        MasterKey::Pes21,
    ];

    /// The raw 64-byte master key.
    fn bytes(self) -> &'static [u8; 64] {
        match self {
            MasterKey::Pes16 => &PES16,
            MasterKey::Pes16MyClub => &PES16_MYCLUB,
            MasterKey::Pes17 => &PES17,
            MasterKey::Pes18 => &PES18,
            MasterKey::Pes19 => &PES19,
            MasterKey::Pes20 => &PES20,
            MasterKey::Pes21 => &PES21,
        }
    }

    /// The key the algorithm uses: `effective[i] = key[(i & !7) + 7 - (i & 7)]` —
    /// each 8-byte block reversed.
    pub(crate) fn effective(self) -> [u8; 64] {
        let key = self.bytes();
        let mut effective = [0u8; 64];
        for (index, byte) in effective.iter_mut().enumerate() {
            *byte = key[(index & !7) + 7 - (index & 7)];
        }
        effective
    }

    /// The game version the key belongs to (`Pes16MyClub` reports `Pes16`).
    pub fn version(self) -> PesVersion {
        match self {
            MasterKey::Pes16 | MasterKey::Pes16MyClub => PesVersion::Pes16,
            MasterKey::Pes17 => PesVersion::Pes17,
            MasterKey::Pes18 => PesVersion::Pes18,
            MasterKey::Pes19 => PesVersion::Pes19,
            MasterKey::Pes20 => PesVersion::Pes20,
            MasterKey::Pes21 => PesVersion::Pes21,
        }
    }

    /// The version's file-header byte length: 176 on PES 16/17, 208 on 18-21.
    pub fn header_size(self) -> usize {
        match self {
            MasterKey::Pes16 | MasterKey::Pes16MyClub | MasterKey::Pes17 => 176,
            MasterKey::Pes18 | MasterKey::Pes19 | MasterKey::Pes20 | MasterKey::Pes21 => 208,
        }
    }
}

